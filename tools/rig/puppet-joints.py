#!/usr/bin/env python3
"""Ball-joint data for the walking puppet -> public/puppet-joints.js (window.XOM_PUPPET).

For every outfit picture (fashion/rig-*.png, 320x400 layer units) this measures:
  neck  [x, y]          pivot the head turns about (centre of the neck skin just under the chin)
  hips  [[x, y], [x, y]] pivots of the left / right leg (centre of each thigh, a little above the crotch)
  hipR  radius of the hip joints (covers the thigh width, so the leg's top edge is an arc around its pivot)
Rounded joints let a limb turn without opening a gap or a jagged seam: the edge between body and limb is a circle
around the pivot, and turning the limb only slides it along that circle.

Run with numpy + Pillow:  python3 tools/rig/puppet-joints.py
"""
import os, re, json
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
PUB = os.path.join(HERE, '..', '..', 'public')
J = json.loads(re.search(r'XOM_RIG_JOINTS=(\{.*\});', open(os.path.join(PUB, 'rig-joints.js')).read()).group(1))

def load(name):
    im = np.array(Image.open(os.path.join(PUB, 'fashion', name + '.png')).convert('RGBA')).astype(int)
    if im.shape[0] != 400:                       # pictures are stored at 2x; measure in layer units
        im = np.array(Image.open(os.path.join(PUB, 'fashion', name + '.png')).convert('RGBA').resize((320, 400), Image.LANCZOS)).astype(int)
    return im

def skin(im):
    r, g, b, a = im[..., 0], im[..., 1], im[..., 2], im[..., 3]
    return (a > 200) & (r > 215) & (g > 150) & (g < 220) & (b > 105) & (b < 195) & (r - g > 22) & (r - g < 90) & (r - b > 40)

def runs(row):
    out, s = [], -1
    for x, on in enumerate(row):
        if on and s < 0: s = x
        if not on and s >= 0:
            out.append((s, x - 1)); s = -1
    if s >= 0: out.append((s, len(row) - 1))
    return out

def main():
    res = {}
    for key, j in sorted(J.items()):
        if not j or not key.startswith('rig-'): continue
        im = load(key); a = im[..., 3] > 110; sk = skin(im)
        sx, cy = j['split'], j['crotch']
        # Neck: skin in the rows just under the chin, near the middle of the figure.
        xs = [x for y in range(218, 232) for x in range(max(0, sx - 70), min(320, sx + 50)) if sk[y, x]]
        nx = float(np.median(xs)) if len(xs) > 20 else float(sx - 8)
        # Thighs: the two runs touching the leg split a few rows under the crotch.
        y = min(cy + 8, 392)
        rr = runs(a[y]); left = [r for r in rr if r[1] <= sx + 2 and r[1] >= sx - 12]; right = [r for r in rr if r[0] >= sx - 2 and r[0] <= sx + 12]
        L = left[-1] if left else (sx - 34, sx - 1); R = right[0] if right else (sx + 1, sx + 34)
        lw, rw = L[1] - L[0], R[1] - R[0]
        lw = min(lw, 46); rw = min(rw, 46)
        hl = [round(sx - lw / 2, 1), cy - 4]; hr = [round(sx + rw / 2, 1), cy - 4]
        # Shoulders: centre of the top of each arm (measured halfway down the arm), radius covering the arm's width.
        sh = []
        for side, arm in (('L', j.get('armL')), ('R', j.get('armR'))):
            if not arm: sh.append(None); continue
            y = (arm['top'] + arm['bottom']) // 2; rr = runs(a[y])
            if side == 'L':
                cand = [r for r in rr if r[1] <= arm['cut'] + 3]; r0 = cand[0] if cand else (arm['cut'] - 28, arm['cut'])
                x0, x1 = r0[0], arm['cut']
            else:
                cand = [r for r in rr if r[0] >= arm['cut'] - 3]; r0 = cand[-1] if cand else (arm['cut'], arm['cut'] + 28)
                x0, x1 = arm['cut'], r0[1]
            w = min(x1 - x0, 44)
            cx = (x1 - w / 2) if side == 'L' else (x0 + w / 2)
            sh.append({'p': [round(cx, 1), arm['top'] + 6], 'r': round(w / 2 + 5, 1)})
        res[key] = {'neck': [round(nx, 1), 224], 'hips': [hl, hr], 'hipR': round(max(lw, rw) / 2 + 5, 1), 'shoulders': sh}
    js = '// Generated by tools/rig/puppet-joints.py: neck / hip pivots and hip radius per outfit (320x400 layer units).\nwindow.XOM_PUPPET=' + json.dumps(res, separators=(',', ':')) + ';\n'
    open(os.path.join(PUB, 'puppet-joints.js'), 'w').write(js)
    for k, v in res.items(): print(k.ljust(24), v)

if __name__ == '__main__':
    main()
